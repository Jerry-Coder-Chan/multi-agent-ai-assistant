"""
Recommendation Agent - Generates personalized recommendations using LLM.
"""
from typing import Dict, List

from agents.llm_client import LLMClient


class RecommendationAgent:
    """Generates event recommendations based on weather and events."""

    def __init__(
        self,
        api_key: str,
        model: str = "gpt-5-mini",
        llm_provider: str = "openai",
        ollama_base_url: str = "",
        qwen_api_key: str = "",
        qwen_base_url: str = "",
    ):
        self.client = LLMClient(
            provider=llm_provider,
            openai_api_key=api_key,
            ollama_base_url=ollama_base_url,
            qwen_api_key=qwen_api_key,
            qwen_base_url=qwen_base_url,
        )
        self.model = model

    def generate_recommendation(
        self,
        weather_data: Dict,
        events: List[Dict]
    ) -> str:
        """
        Generate personalized recommendations.

        Args:
            weather_data: Weather information dictionary
            events: List of available events

        Returns:
            Recommendation text
        """
        # Build context
        context = self._build_context(weather_data, events)

        try:
            return self.client.chat(
                messages=[
                    {"role": "system", "content": self._get_system_prompt()},
                    {"role": "user", "content": context},
                ],
                model=self.model,
                temperature=0.7,
            )
        except Exception as e:
            # Fail open for local LLM timeouts: return deterministic, weather-aware suggestions.
            err = str(e).lower()
            if "read timed out" in err or "timeout" in err or "connectionpool" in err:
                return self._fallback_recommendation(weather_data, events)
            raise Exception(f"Recommendation generation error: {str(e)}")

    def _build_context(self, weather_data: Dict, events: List[Dict]) -> str:
        """Build context string for LLM."""
        context = f"""Weather Conditions:
- Condition: {weather_data.get('condition', 'Unknown')}
- Temperature: {weather_data.get('temperature_c', 'N/A')}°C
- UV Index: {weather_data.get('uv_index', 'N/A')}
- Chance of Rain: {weather_data.get('rain_chance', 'N/A')}%
- Humidity: {weather_data.get('humidity', 'N/A')}%

Available Events:
"""
        for event in events:
            context += f"""
- {event.get('name', 'N/A')} ({event.get('type', 'N/A')})
  Time: {event.get('time', 'N/A')}
  Price: ${event.get('price', 0):.2f}
  Capacity: {event.get('capacity', 'N/A')}
  Description: {event.get('description', 'N/A')}
"""
        return context

    def _get_system_prompt(self) -> str:
        """Return system prompt for recommendation agent."""
        return """You are Amanda, a professional tourism advisor and customer service assistant for travelers.
Use a friendly, customer-first, less formal tone with light emojis where appropriate.
Keep the language natural and conversational while staying professional.

Your task:
1. Analyze weather conditions and suggest appropriate events
2. For bad weather (rain, extreme heat), prioritize indoor events
3. For good weather, suggest outdoor activities
4. Group recommendations by time of day (Morning, Afternoon, Evening)
5. Consider price and capacity when recommending
6. Provide transport suggestions based on weather
7. Be concise but informative

Output format requirements (strict):
- Use markdown headings for time blocks when relevant (e.g., Morning, Afternoon, Evening).
- Use one bullet per activity (never combine multiple activities into one bullet).
- For each bullet, use this pattern:
  - **Activity Name** — Why it's suitable; key details (price/capacity/tips)
- Keep each bullet to 1-2 short sentences for readability.
- End with 1 short follow-up question.

Prefer practical guidance that helps tourists decide quickly."""

    def _fallback_recommendation(self, weather_data: Dict, events: List[Dict]) -> str:
        """Deterministic fallback when LLM provider times out/unavailable."""
        rain = float(weather_data.get("rain_chance", 0) or 0)
        temp = float(weather_data.get("temperature_c", 0) or 0)
        prefer_indoor = rain >= 60 or temp >= 33

        ranked = []
        for e in events:
            is_indoor = bool(e.get("indoor"))
            score = 0
            if prefer_indoor and is_indoor:
                score += 3
            if not prefer_indoor and not is_indoor:
                score += 3
            price = float(e.get("price", 0) or 0)
            if price == 0:
                score += 2
            elif price <= 20:
                score += 1
            ranked.append((score, e))

        ranked.sort(key=lambda x: x[0], reverse=True)
        picks = [e for _, e in ranked[:4]]

        lines = []
        if prefer_indoor:
            lines.append("Given today's weather, indoor options are the best fit:")
        else:
            lines.append("Weather looks favorable, here are good picks for today:")
        lines.append("")
        for e in picks:
            lines.append(
                f"- **{e.get('name', 'Activity')}** — {e.get('type', 'Event')}, "
                f"{e.get('time', 'N/A')} at {e.get('location', 'N/A')}; "
                f"price ${float(e.get('price', 0) or 0):.2f}."
            )
        lines.append("")
        lines.append("I can also filter by free-only, indoor-only, or evening options.")
        return "\n".join(lines)
